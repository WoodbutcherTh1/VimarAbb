// Writes the deploy-time basePath as a literal source file rather than
// relying on NEXT_PUBLIC_ env inlining, which doesn't reliably reach
// re-hydrated client chunks under Turbopack in this Next.js build.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const basePath = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
const outFile = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "basePath.generated.ts");

writeFileSync(
  outFile,
  `// Auto-generated by scripts/generate-base-path.mjs — do not edit by hand.\nexport const BASE_PATH = ${JSON.stringify(basePath)};\n`
);

console.log(`[generate-base-path] BASE_PATH=${JSON.stringify(basePath)} -> ${outFile}`);
